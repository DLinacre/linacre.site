// One-off generator: converts Natural Earth 110m land polygons (public domain)
// into a compact equirectangular SVG path (viewBox 0 0 360 180) used by the
// Orbit page world map. Usage: node scripts/build-world-path.mjs <ne_110m_land.geojson>
import fs from 'node:fs';
import path from 'node:path';

const input = process.argv[2];
if (!input) {
  console.error('Usage: node scripts/build-world-path.mjs <ne_110m_land.geojson>');
  process.exit(1);
}

const geo = JSON.parse(fs.readFileSync(input, 'utf8'));
const r = n => Math.round(n * 10) / 10;
const rings = [];
for (const f of geo.features) {
  const g = f.geometry;
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  for (const poly of polys) for (const ring of poly) rings.push(ring);
}

let d = '';
for (const ring of rings) {
  let last = '';
  let seg = '';
  let count = 0;
  for (const [lon, lat] of ring) {
    const pt = `${r(lon + 180)} ${r(90 - lat)}`;
    if (pt === last) continue;
    seg += (count === 0 ? 'M' : 'L') + pt;
    last = pt;
    count++;
  }
  if (count > 2) d += seg + 'Z';
}

const out = `// Generated by scripts/build-world-path.mjs from Natural Earth 110m land (public domain).
// Equirectangular projection, viewBox "0 0 360 180" (x = lon + 180, y = 90 - lat).
export const WORLD_LAND_PATH =
  '${d}';
`;
fs.writeFileSync(path.join('src', 'data', 'worldLand.ts'), out);
console.log(`Wrote ${rings.length} rings, ${d.length} chars`);
